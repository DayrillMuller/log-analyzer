_MAX_STORED_LINE_NUMBERS = 1000


def _compile_regex(pattern_str: str, flags: int, context: str) -> Pattern[str]:
    """Compile a regex pattern and raise a clear ValueError on malformed syntax."""
    if not isinstance(pattern_str, str) or not pattern_str:
        raise ValueError(f"Invalid empty or non-string regex pattern in {context}.")
    try:
        return re.compile(pattern_str, flags)
    except re.error as exc:
        raise ValueError(
            f"Malformed regex in {context} (pattern={pattern_str!r}): {exc}"
        ) from exc


def _format_timestamp(dt: Optional[datetime]) -> Optional[str]:
    if dt is None:
        return None
    return dt.strftime("%Y-%m-%dT%H:%M:%SZ")


def _truncate(text: str, max_len: int = 120) -> str:
    cleaned = " ".join(text.split())
    if len(cleaned) <= max_len:
        return cleaned
    return cleaned[: max_len - 3] + "..."


def _format_line_range(line_numbers: list[int], total_hits: int) -> str:
    if not line_numbers:
        return "N/A"
    if len(line_numbers) == 1 and total_hits == 1:
        return f"line {line_numbers[0]}"
    first, last = min(line_numbers), max(line_numbers)
    if len(line_numbers) <= 5 and total_hits <= 5:
        joined = ", ".join(str(n) for n in line_numbers)
        return f"lines {joined}"
    return f"lines {first}-{last} ({total_hits} hits)"


def load_rules(rules_path: Optional[Union[str, Path]] = None) -> RuleSet:
    """Load, validate, and pre-compile all rules, allowlists, and dedup settings from YAML."""
    path = Path(rules_path) if rules_path is not None else DEFAULT_RULES_PATH
    if not path.is_file():
        raise FileNotFoundError(f"Rules file not found: {path}")

    try:
        with path.open("r", encoding="utf-8") as fh:
            raw_config = yaml.safe_load(fh)
    except yaml.YAMLError as exc:
        raise ValueError(f"Failed to parse YAML in '{path}': {exc}") from exc

    if not isinstance(raw_config, dict):
        raise ValueError(f"Invalid rules YAML structure in '{path}': expected a mapping.")

    # 1. Allowlist configuration
    allowlist_raw = raw_config.get("allowlist") or {}
    if not isinstance(allowlist_raw, dict):
        raise ValueError(f"Invalid 'allowlist' section in '{path}': expected a mapping.")

    networks: list[IPNetwork] = []
    for raw_cidr in allowlist_raw.get("ips_and_cidrs") or []:
        try:
            networks.append(ipaddress.ip_network(str(raw_cidr).strip(), strict=False))
        except ValueError as exc:
            raise ValueError(
                f"Invalid IP/CIDR '{raw_cidr}' in allowlist of '{path}': {exc}"
            ) from exc

    safe_paths = frozenset(
        str(p).strip().lower() for p in (allowlist_raw.get("paths") or []) if str(p).strip()
    )
    ua_patterns = tuple(
        _compile_regex(str(p), re.IGNORECASE, context="allowlist.user_agents")
        for p in (allowlist_raw.get("user_agents") or [])
    )
    allowlist = AllowlistConfig(
        networks=tuple(networks),
        paths=safe_paths,
        user_agent_patterns=ua_patterns,
    )

    # 2. Deduplication configuration
    dedup_raw = raw_config.get("deduplication") or {}
    if not isinstance(dedup_raw, dict):
        raise ValueError(f"Invalid 'deduplication' section in '{path}': expected a mapping.")
    dedup_cooldown = int(dedup_raw.get("cooldown_seconds", 300))
    dedup_samples = int(dedup_raw.get("max_samples", 3))
    if dedup_cooldown < 0 or dedup_samples < 1:
        raise ValueError(
            "Invalid 'deduplication' config: cooldown_seconds must be >= 0 and max_samples >= 1."
        )
    deduplication = DeduplicationConfig(
        enabled=bool(dedup_raw.get("enabled", True)),
        cooldown_seconds=dedup_cooldown,
        max_samples=dedup_samples,
    )

    # 3. Signature rules (pre-compiled & validated)
    signatures: list[SignatureRule] = []
    for item in raw_config.get("signatures") or []:
        rule_id = str(item.get("id", "<unnamed>"))
        if "name" not in item or "severity" not in item:
            raise ValueError(f"Signature rule '{rule_id}' must define 'id', 'name', and 'severity'.")
        flags = 0 if item.get("case_sensitive", False) else re.IGNORECASE
        raw_patterns = item.get("patterns") or []
        if not raw_patterns:
            raise ValueError(f"Signature rule '{rule_id}' must define at least one pattern.")
        compiled = tuple(
            _compile_regex(str(p), flags, context=f"signature rule '{rule_id}'")
            for p in raw_patterns
        )
        fields = tuple(str(f) for f in (item.get("fields") or ("message", "endpoint_or_service")))
        formats = frozenset(str(f).lower() for f in (item.get("formats") or ()))
        signatures.append(
            SignatureRule(
                id=rule_id,
                name=str(item["name"]),
                category=str(item.get("category", "signature")),
                severity=Severity.from_str(str(item["severity"])),
                fields=fields,
                patterns=compiled,
                remediation_hint=str(
                    item.get("remediation_hint", "Investigate event and review host/WAF logs.")
                ),
                url_decode=bool(item.get("url_decode", False)),
                formats=formats,
            )
        )

    # 4. Behavioral rules (pre-compiled & validated)
    behavioral_rules: list[BehavioralRule] = []
    for item in raw_config.get("behavioral_rules") or []:
        rule_id = str(item.get("id", "<unnamed>"))
        threshold = int(item["threshold"])
        window_seconds = int(item["window_seconds"])
        if threshold < 1 or window_seconds < 1:
            raise ValueError(
                f"Behavioral rule '{rule_id}' must have threshold >= 1 and window_seconds >= 1."
            )
        match_cfg = item.get("match") or {}
        status_codes = frozenset(int(code) for code in (match_cfg.get("status_codes") or []))
        msg_patterns = tuple(
            _compile_regex(str(p), re.IGNORECASE, context=f"behavioral rule '{rule_id}'")
            for p in (match_cfg.get("message_patterns") or [])
        )
        match_all = bool(match_cfg.get("match_all", False))
        if not (match_all or status_codes or msg_patterns):
            raise ValueError(
                f"Behavioral rule '{rule_id}' must specify match criteria "
                "(status_codes, message_patterns, or match_all)."
            )
        behavioral_rules.append(
            BehavioralRule(
                id=rule_id,
                name=str(item["name"]),
                category=str(item.get("category", "behavioral")),
                severity=Severity.from_str(str(item["severity"])),
                threshold=threshold,
                window_seconds=window_seconds,
                remediation_hint=str(
                    item.get("remediation_hint", "Rate-limit or block offending source IP.")
                ),
                status_codes=status_codes,
                message_patterns=msg_patterns,
                match_all=match_all,
            )
        )

    return RuleSet(
        signatures=signatures,
        behavioral_rules=behavioral_rules,
        allowlist=allowlist,
        deduplication=deduplication,
    )


class DetectionEngine:
    """Two-layer detection engine with allowlisting, smart deduplication, and TTL-bounded memory."""

    def __init__(
        self,
        rules: Optional[RuleSet] = None,
        *,
        cleanup_interval: int = 1000,
        max_tracked_ips: int = 100_000,
    ) -> None:
        if cleanup_interval < 1:
            raise ValueError("cleanup_interval must be >= 1.")
        if max_tracked_ips < 1:
            raise ValueError("max_tracked_ips must be >= 1.")

        self.rules: RuleSet = rules if rules is not None else load_rules()
        self.cleanup_interval: int = cleanup_interval
        self.max_tracked_ips: int = max_tracked_ips

        self._windows: dict[tuple[str, str], Deque[_WindowEvent]] = {}
        self._active_bursts: dict[tuple[str, str], _ActiveBurst] = {}
        self._dedup_groups: dict[tuple[str, str], _DedupGroup] = {}
        self._rule_by_id: dict[str, BehavioralRule] = {
            rule.id: rule for rule in self.rules.behavioral_rules
        }
        self._entries_since_cleanup: int = 0
        self._latest_ts: Optional[datetime] = None
        self.allowlisted_count: int = 0

    @property
    def tracked_window_count(self) -> int:
        """Number of active (rule_id, source_ip) sliding windows currently in memory."""
        return len(self._windows)

    @property
    def active_burst_count(self) -> int:
        """Number of open behavioral burst incidents currently in memory."""
        return len(self._active_bursts)

    @property
    def active_dedup_group_count(self) -> int:
        """Number of open signature deduplication groups currently in memory."""
        return len(self._dedup_groups)

    def reset(self) -> None:
        """Clear all stateful tracking buffers and counters."""
        self._windows.clear()
        self._active_bursts.clear()
        self._dedup_groups.clear()
        self._entries_since_cleanup = 0
        self._latest_ts = None
        self.allowlisted_count = 0

    def _extract_candidate_texts(self, entry: LogEntry, rule: SignatureRule) -> list[str]:
        texts: list[str] = []
        for field_name in rule.fields:
            value = getattr(entry, field_name, None)
            if not value:
                continue
            text = str(value)
            texts.append(text)
            if rule.url_decode and "%" in text:
                decoded = unquote(text)
                if decoded != text:
                    texts.append(decoded)
        return texts

    def _build_dedup_finding(self, group: _DedupGroup) -> Finding:
        first_str = _format_timestamp(group.first_ts)
        last_str = _format_timestamp(group.last_ts)
        if first_str and last_str and first_str != last_str:
            ts_display: Optional[str] = f"{first_str} -> {last_str}"
        else:
            ts_display = first_str or last_str

        if group.hit_count == 1:
            evidence = group.sample_evidence[0]
        else:
            line_summary = _format_line_range(group.line_numbers, group.hit_count)
            joined_samples = " | ".join(group.sample_evidence)
            evidence = (
                f"{group.hit_count} occurrences ({line_summary}); "
                f"samples: {joined_samples}"
            )

        return Finding(
            rule_id=group.rule.id,
            rule_name=group.rule.name,
            severity=group.rule.severity,
            source_ip=group.source_ip,
            timestamp=ts_display,
            evidence=evidence,
            remediation_hint=group.rule.remediation_hint,
            line_numbers=list(group.line_numbers),
            category=group.rule.category,
            hit_count=group.hit_count,
            first_seen=first_str,
            last_seen=last_str,
            sample_evidence=list(group.sample_evidence),
        )

    def _evaluate_signatures(
        self,
        entry: LogEntry,
        log_format: Optional[str] = None,
    ) -> list[Finding]:
        emitted: list[Finding] = []
        dedup_cfg = self.rules.deduplication
        cooldown_delta = timedelta(seconds=dedup_cfg.cooldown_seconds)

        for rule in self.rules.signatures:
            if not rule.applies_to(log_format):
                continue

            candidate_texts = self._extract_candidate_texts(entry, rule)
            matched_text: Optional[str] = None
            matched_fragment: Optional[str] = None

            for text in candidate_texts:
                for pattern in rule.patterns:
                    match = pattern.search(text)
                    if match:
                        matched_text = text
                        matched_fragment = match.group(0)
                        break
                if matched_text is not None:
                    break

            if matched_text is None or matched_fragment is None:
                continue

            sample_line = (
                f'Line {entry.line_number}: matched "{_truncate(matched_fragment, 50)}" '
                f'in "{_truncate(matched_text, 95)}"'
            )

            if not dedup_cfg.enabled:
                ts_str = _format_timestamp(entry.timestamp)
                emitted.append(
                    Finding(
                        rule_id=rule.id,
                        rule_name=rule.name,
                        severity=rule.severity,
                        source_ip=entry.source_ip,
                        timestamp=ts_str,
                        evidence=sample_line,
                        remediation_hint=rule.remediation_hint,
                        line_numbers=[entry.line_number],
                        category=rule.category,
                        hit_count=1,
                        first_seen=ts_str,
                        last_seen=ts_str,
                        sample_evidence=[sample_line],
                    )
                )
                continue

            key = (rule.id, entry.source_ip or "__no_ip__")
            existing = self._dedup_groups.get(key)
            if existing is not None:
                within_cooldown = (
                    entry.timestamp is None
                    or existing.last_ts is None
                    or (entry.timestamp - existing.last_ts) <= cooldown_delta
                )
                if within_cooldown:
                    existing.hit_count += 1
                    if entry.timestamp is not None:
                        if existing.first_ts is None or entry.timestamp < existing.first_ts:
                            existing.first_ts = entry.timestamp
                        if existing.last_ts is None or entry.timestamp > existing.last_ts:
                            existing.last_ts = entry.timestamp
                    if len(existing.line_numbers) < _MAX_STORED_LINE_NUMBERS:
                        existing.line_numbers.append(entry.line_number)
                    if len(existing.sample_evidence) < dedup_cfg.max_samples:
                        existing.sample_evidence.append(sample_line)
                    continue

                # Cooldown expired -> emit previous aggregated finding and start a fresh group
                emitted.append(self._build_dedup_finding(existing))

            self._dedup_groups[key] = _DedupGroup(
                rule=rule,
                source_ip=entry.source_ip,
                first_ts=entry.timestamp,
                last_ts=entry.timestamp,
                hit_count=1,
                line_numbers=[entry.line_number],
                sample_evidence=[sample_line],
            )

        return emitted

    def _build_burst_finding(
        self,
        rule: BehavioralRule,
        source_ip: str,
        burst: _ActiveBurst,
    ) -> Finding:
        start_str = _format_timestamp(burst.start_ts)
        end_str = _format_timestamp(burst.last_ts)
        ts_display = (
            start_str
            if start_str == end_str
            else f"{start_str or 'N/A'} -> {end_str or 'N/A'}"
        )
        span_seconds = max(0, int((burst.last_ts - burst.start_ts).total_seconds()))
        sample_lines = [f'"{_truncate(s, 80)}"' for s in burst.sample_snippets]
        sample_summary = ", ".join(sample_lines) if sample_lines else '""'
        evidence = (
            f"{burst.hit_count} events in {span_seconds}s "
            f"(threshold: {rule.threshold}/{rule.window_seconds}s); "
            f"{_format_line_range(burst.line_numbers, burst.hit_count)}; "
            f"samples: {sample_summary}"
        )
        return Finding(
            rule_id=rule.id,
            rule_name=rule.name,
            severity=rule.severity,
            source_ip=source_ip,
            timestamp=ts_display,
            evidence=evidence,
            remediation_hint=rule.remediation_hint,
            line_numbers=list(burst.line_numbers),
            category=rule.category,
            hit_count=burst.hit_count,
            first_seen=start_str,
            last_seen=end_str,
            sample_evidence=list(burst.sample_snippets),
        )

    def _evaluate_behavioral(self, entry: LogEntry) -> list[Finding]:
        if entry.source_ip is None or entry.timestamp is None:
            return []

        emitted: list[Finding] = []
        event_ts = entry.timestamp
        snippet = entry.endpoint_or_service or entry.message or entry.raw_line
        max_samples = self.rules.deduplication.max_samples

        for rule in self.rules.behavioral_rules:
            if not rule.matches(entry):
                continue

            key = (rule.id, entry.source_ip)
            window_delta = timedelta(seconds=rule.window_seconds)

            active = self._active_bursts.get(key)
            if active is not None:
                if event_ts - active.last_ts <= window_delta:
                    active.last_ts = max(active.last_ts, event_ts)
                    active.hit_count += 1
                    if len(active.line_numbers) < _MAX_STORED_LINE_NUMBERS:
                        active.line_numbers.append(entry.line_number)
                    if len(active.sample_snippets) < max_samples:
                        active.sample_snippets.append(snippet)
                    continue
                emitted.append(self._build_burst_finding(rule, entry.source_ip, active))
                del self._active_bursts[key]
                self._windows.pop(key, None)

            window = self._windows.pop(key, None)
            if window is None:
                window = deque()
            # Re-insert at the end to maintain recency ordering for bounded LRU eviction
            self._windows[key] = window

            window.append(
                _WindowEvent(
                    timestamp=event_ts,
                    line_number=entry.line_number,
                    snippet=snippet,
                )
            )

            cutoff = event_ts - window_delta
            while window and window[0].timestamp < cutoff:
                window.popleft()

            if len(window) >= rule.threshold:
                self._active_bursts[key] = _ActiveBurst(
                    start_ts=min(ev.timestamp for ev in window),
                    last_ts=max(ev.timestamp for ev in window),
                    line_numbers=[ev.line_number for ev in window][:_MAX_STORED_LINE_NUMBERS],
                    sample_snippets=[ev.snippet for ev in list(window)[:max_samples]],
                    hit_count=len(window),
                )
                del self._windows[key]

        return emitted

    def cleanup_expired_state(
        self,
        reference_time: Optional[datetime] = None,
    ) -> list[Finding]:
        """Evict expired timestamps, inactive IP windows, and expired bursts/groups to bound memory."""
        ref = reference_time if reference_time is not None else self._latest_ts
        emitted: list[Finding] = []

        if ref is not None:
            # 1. Evict expired events and delete empty per-IP sliding windows
            stale_window_keys: list[tuple[str, str]] = []
            for key, window in self._windows.items():
                rule = self._rule_by_id[key[0]]
                cutoff = ref - timedelta(seconds=rule.window_seconds)
                while window and window[0].timestamp < cutoff:
                    window.popleft()
                if not window:
                    stale_window_keys.append(key)
            for key in stale_window_keys:
                del self._windows[key]

            # 2. Finalize expired active behavioral bursts
            expired_bursts: list[tuple[str, str]] = []
            for key, burst in self._active_bursts.items():
                rule = self._rule_by_id[key[0]]
                if (ref - burst.last_ts) > timedelta(seconds=rule.window_seconds):
                    emitted.append(self._build_burst_finding(rule, key[1], burst))
                    expired_bursts.append(key)
            for key in expired_bursts:
                del self._active_bursts[key]

            # 3. Finalize expired signature deduplication groups
            cooldown = timedelta(seconds=self.rules.deduplication.cooldown_seconds)
            expired_groups: list[tuple[str, str]] = []
            for key, group in self._dedup_groups.items():
                if group.last_ts is not None and (ref - group.last_ts) > cooldown:
                    emitted.append(self._build_dedup_finding(group))
                    expired_groups.append(key)
            for key in expired_groups:
                del self._dedup_groups[key]

        # 4. Hard memory cap safety valve (evict least-recently-active IP windows first)
        while len(self._windows) > self.max_tracked_ips:
            oldest_key = next(iter(self._windows))
            del self._windows[oldest_key]

        return emitted

    def process_entry(
        self,
        entry: LogEntry,
        log_format: Optional[str] = None,
    ) -> list[Finding]:
        """Process a single LogEntry through allowlist, signature, behavioral, and TTL cleanup."""
        if entry.timestamp is not None:
            if self._latest_ts is None or entry.timestamp > self._latest_ts:
                self._latest_ts = entry.timestamp

        if self.rules.allowlist.is_allowed(entry):
            self.allowlisted_count += 1
            return []

        findings = self._evaluate_signatures(entry, log_format=log_format)
        findings.extend(self._evaluate_behavioral(entry))

        self._entries_since_cleanup += 1
        if self._entries_since_cleanup >= self.cleanup_interval:
            self._entries_since_cleanup = 0
            findings.extend(self.cleanup_expired_state())

        return findings

    def finalize(self) -> list[Finding]:
        """Flush all remaining open deduplication groups and behavioral bursts at end-of-stream."""
        emitted: list[Finding] = []
        for group in self._dedup_groups.values():
            emitted.append(self._build_dedup_finding(group))
        self._dedup_groups.clear()

        for (rule_id, source_ip), burst in self._active_bursts.items():
            rule = self._rule_by_id[rule_id]
            emitted.append(self._build_burst_finding(rule, source_ip, burst))
        self._active_bursts.clear()
        self._windows.clear()
        return emitted

    def analyze(
        self,
        entries: Iterable[LogEntry],
        *,
        input_source: str = "<stream>",
        detected_format: str = "generic",
        min_severity: Severity = Severity.LOW,
        parse_stats: Optional[ParseStats] = None,
    ) -> AnalysisResult:
        """Stream through all LogEntry objects and produce a complete AnalysisResult."""
        self.reset()
        started = time.perf_counter()

        local_stats = parse_stats if parse_stats is not None else ParseStats()
        track_local_stats = parse_stats is None

        processed_entries = 0
        seen_ips: set[str] = set()
        all_findings: list[Finding] = []

        for entry in entries:
            processed_entries += 1
            if track_local_stats:
                local_stats.total_lines += 1
                if entry.is_malformed:
                    local_stats.malformed_lines += 1
                else:
                    local_stats.parsed_lines += 1

            if entry.source_ip:
                seen_ips.add(entry.source_ip)
            all_findings.extend(self.process_entry(entry, log_format=detected_format))

        all_findings.extend(self.finalize())

        filtered = [f for f in all_findings if f.severity >= min_severity]
        filtered.sort(
            key=lambda f: (
                -int(f.severity),
                f.line_numbers[0] if f.line_numbers else 0,
                f.rule_id,
            )
        )

        severity_counts = {sev.name: 0 for sev in reversed(Severity)}
        ip_finding_counts: Counter[str] = Counter()
        for finding in filtered:
            severity_counts[finding.severity.name] += 1
            if finding.source_ip:
                ip_finding_counts[finding.source_ip] += finding.hit_count

        elapsed = time.perf_counter() - started
        total_lines = local_stats.total_lines if local_stats.total_lines > 0 else processed_entries
        return AnalysisResult(
            input_source=input_source,
            detected_format=detected_format,
            total_lines=total_lines,
            findings=filtered,
            severity_counts=severity_counts,
            unique_ips=len(seen_ips),
            top_offending_ips=ip_finding_counts.most_common(10),
            elapsed_seconds=elapsed,
            min_severity=min_severity,
            parse_stats=local_stats,
            allowlisted_count=self.allowlisted_count,
        )
