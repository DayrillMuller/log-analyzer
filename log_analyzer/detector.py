class Severity(IntEnum):
    """Ordered alert severity levels."""

    LOW = 1
    MEDIUM = 2
    HIGH = 3
    CRITICAL = 4

    @classmethod
    def from_str(cls, value: str) -> "Severity":
        normalized = value.strip().upper()
        try:
            return cls[normalized]
        except KeyError as exc:
            valid = ", ".join(member.name for member in cls)
            raise ValueError(
                f"Invalid severity '{value}'. Expected one of: {valid}."
            ) from exc


@dataclass(slots=True)
class Finding:
    """Structured security or anomaly alert generated by the detection engine."""

    rule_id: str
    rule_name: str
    severity: Severity
    source_ip: Optional[str]
    timestamp: Optional[str]
    evidence: str
    remediation_hint: str
    line_numbers: list[int] = field(default_factory=list)
    category: str = "general"
    hit_count: int = 1
    first_seen: Optional[str] = None
    last_seen: Optional[str] = None
    sample_evidence: list[str] = field(default_factory=list)

    @property
    def event_count(self) -> int:
        """Backward-compatible alias for hit_count."""
        return self.hit_count

    def to_dict(self) -> dict[str, Any]:
        return {
            "rule_id": self.rule_id,
            "rule_name": self.rule_name,
            "severity": self.severity.name,
            "category": self.category,
            "source_ip": self.source_ip or "N/A",
            "timestamp": self.timestamp or "N/A",
            "first_seen": self.first_seen or self.timestamp or "N/A",
            "last_seen": self.last_seen or self.timestamp or "N/A",
            "hit_count": self.hit_count,
            "line_numbers": list(self.line_numbers),
            "sample_evidence": list(self.sample_evidence),
            "evidence": self.evidence,
            "remediation_hint": self.remediation_hint,
        }


@dataclass(slots=True)
class AllowlistConfig:
    """Trusted IPs/CIDRs, exact safe request paths, and benign User-Agent patterns."""

    networks: tuple[IPNetwork, ...] = field(default_factory=tuple)
    paths: frozenset[str] = field(default_factory=frozenset)
    user_agent_patterns: tuple[Pattern[str], ...] = field(default_factory=tuple)

    def is_allowed(self, entry: LogEntry) -> bool:
        """Return True if the entry matches any configured allowlist exclusion."""
        if self.networks and entry.source_ip:
            try:
                ip_obj = ipaddress.ip_address(entry.source_ip)
                if any(ip_obj in net for net in self.networks):
                    return True
            except ValueError:
                pass

        # Match exact safe path only (query strings are NOT stripped to prevent bypasses)
        if self.paths and entry.request_path:
            if entry.request_path.strip().lower() in self.paths:
                return True

        if self.user_agent_patterns and entry.user_agent:
            if any(pat.search(entry.user_agent) for pat in self.user_agent_patterns):
                return True

        return False


@dataclass(slots=True)
class DeduplicationConfig:
    """Configuration for aggregating repeated signature alerts per (rule_id, source_ip)."""

    enabled: bool = True
    cooldown_seconds: int = 300
    max_samples: int = 3


@dataclass(slots=True)
class SignatureRule:
    """Compiled stateless regex detection rule."""

    id: str
    name: str
    category: str
    severity: Severity
    fields: tuple[str, ...]
    patterns: tuple[Pattern[str], ...]
    remediation_hint: str
    url_decode: bool = False
    formats: frozenset[str] = field(default_factory=frozenset)

    def applies_to(self, log_format: Optional[str]) -> bool:
        if not self.formats or "all" in self.formats or not log_format:
            return True
        return log_format.lower() in self.formats


@dataclass(slots=True)
class BehavioralRule:
    """Compiled stateful sliding-window behavioral rule."""

    id: str
    name: str
    category: str
    severity: Severity
    threshold: int
    window_seconds: int
    remediation_hint: str
    status_codes: frozenset[int] = field(default_factory=frozenset)
    message_patterns: tuple[Pattern[str], ...] = field(default_factory=tuple)
    match_all: bool = False

    def matches(self, entry: LogEntry) -> bool:
        if self.match_all:
            return True
        if self.status_codes and entry.status_code in self.status_codes:
            return True
        if self.message_patterns:
            target = entry.message or entry.raw_line
            return any(pattern.search(target) for pattern in self.message_patterns)
        return False


